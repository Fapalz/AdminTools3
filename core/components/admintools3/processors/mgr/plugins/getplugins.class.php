/**
 * Get plugins
 */
class AdminTools3PluginChoicesProcessor extends modObjectGetListProcessor {
    public $objectType = 'admintools3_plugin';
    public $classKey = 'modPlugin';
//    public $languageTopics = array('admintools3:default');
    public $defaultSortField = 'name';
    public $defaultSortDirection = 'ASC';
    public $permission = 'edit_plugin';

    /**
     * @param xPDOQuery $c
     *
     * @return xPDOQuery
     */
    public function prepareQueryBeforeCount(xPDOQuery $c) {
        $query = trim($this->getProperty('query'));
        if ($query) {
            $c->where(array(
                'name:LIKE' => "%{$query}%",
            ));
        }

        return $c;
    }
}
return AdminTools3PluginChoicesProcessor::class;
